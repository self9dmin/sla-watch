import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIRECTORY_ORIGIN = "https://sla.directory";
const DIRECTORY_INDEX_URL = `${DIRECTORY_ORIGIN}/`;
const REQUEST_TIMEOUT_MS = 10_000;
const MAX_SVG_BYTES = 100_000;
const CONCURRENCY = 12;
const MIN_EXPECTED_LOGOS = 250;

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const outputDirectory = path.join(repositoryRoot, "ui", "assets", "providers");
const manifestPath = path.join(repositoryRoot, "ui", "app", "data", "providerLogoSlugs.ts");

const fetchText = async (url) => {
  const response = await fetch(url, {
    headers: { accept: "image/svg+xml,text/html;q=0.9,*/*;q=0.1" },
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  });

  if (!response.ok) {
    throw new Error(`${url} returned HTTP ${response.status}`);
  }

  const body = await response.text();
  if (Buffer.byteLength(body, "utf8") > MAX_SVG_BYTES && url.endsWith(".svg")) {
    throw new Error(`${url} exceeds the ${MAX_SVG_BYTES}-byte SVG limit`);
  }
  return body;
};

const discoverLogoSlugs = (html) => Array.from(new Set(
  Array.from(html.matchAll(/\/logos\/([a-z0-9]+(?:-[a-z0-9]+)*)\.svg/g), (match) => match[1]),
)).sort();

const assertSafeSvg = (svg, slug) => {
  if (!/<svg(?:\s|>)/i.test(svg)) {
    throw new Error(`${slug}.svg does not contain an SVG root element`);
  }

  const forbiddenMarkup = [
    [/<\s*script\b/i, "script element"],
    [/<\s*foreignObject\b/i, "foreignObject element"],
    [/<\s*(?:iframe|object|embed)\b/i, "embedded document element"],
    [/<!DOCTYPE\b/i, "document type declaration"],
    [/<!ENTITY\b/i, "entity declaration"],
    [/\son[a-z]+\s*=/i, "inline event handler"],
    [/javascript\s*:/i, "javascript URL"],
    [/@import\b/i, "CSS import"],
  ];

  for (const [pattern, description] of forbiddenMarkup) {
    if (pattern.test(svg)) {
      throw new Error(`${slug}.svg contains a forbidden ${description}`);
    }
  }

  for (const match of svg.matchAll(/\b(?:href|xlink:href)\s*=\s*(["'])(.*?)\1/gi)) {
    const reference = match[2].trim();
    if (reference && !reference.startsWith("#")) {
      throw new Error(`${slug}.svg contains a non-local href reference`);
    }
  }

  for (const match of svg.matchAll(/url\s*\(\s*(["']?)(.*?)\1\s*\)/gi)) {
    const reference = match[2].trim();
    if (reference && !reference.startsWith("#")) {
      throw new Error(`${slug}.svg contains a non-local CSS URL reference`);
    }
  }
};

const manifestSource = (slugs) => `/**
 * Generated by scripts/vendor-provider-logos.mjs from ${DIRECTORY_INDEX_URL}
 * The app serves these marks locally. Provider detection remains tenant-driven.
 */
export const BUNDLED_PROVIDER_LOGO_SLUGS = ${JSON.stringify(slugs, null, 2)} as const;

const bundledProviderLogoSlugs = new Set<string>(BUNDLED_PROVIDER_LOGO_SLUGS);

export const hasBundledProviderLogo = (slug: string): boolean => bundledProviderLogoSlugs.has(slug);
`;

const main = async () => {
  const directoryHtml = await fetchText(DIRECTORY_INDEX_URL);
  const slugs = discoverLogoSlugs(directoryHtml);
  if (slugs.length < MIN_EXPECTED_LOGOS) {
    throw new Error(`Only ${slugs.length} provider logos were discovered; expected at least ${MIN_EXPECTED_LOGOS}`);
  }

  const queue = [...slugs];
  const downloadedLogos = new Map();

  const worker = async () => {
    while (queue.length > 0) {
      const slug = queue.shift();
      if (!slug) return;
      const svg = await fetchText(`${DIRECTORY_ORIGIN}/logos/${slug}.svg`);
      assertSafeSvg(svg, slug);
      downloadedLogos.set(slug, svg);
    }
  };

  await Promise.all(Array.from({ length: Math.min(CONCURRENCY, slugs.length) }, () => worker()));
  await mkdir(outputDirectory, { recursive: true });
  await Promise.all(slugs.map((slug) => (
    writeFile(path.join(outputDirectory, `${slug}.svg`), downloadedLogos.get(slug), "utf8")
  )));
  await writeFile(manifestPath, manifestSource(slugs), "utf8");
  process.stdout.write(`Vendored ${downloadedLogos.size} provider SVGs from ${DIRECTORY_ORIGIN}.\n`);
};

await main();
